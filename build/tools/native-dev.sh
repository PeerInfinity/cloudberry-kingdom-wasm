#!/usr/bin/env bash
# native-dev.sh — A native Linux build of the browser compile set, for fast generator-API work (seconds, not the
# AOT publish's minutes). Same C# as the page, without the BROWSER define; generates byte-identical ck-level documents
# apart from engine.build (measured in P0). A development oracle only: the page is what ships.
#
# Usage:  build/tools/native-dev.sh --site <built site> --libs <dir> --out <run dir> [--dotnet <dotnet>]
#   --site   a site built by build/build.sh (its Content/ is copied: the engine-only content)
#   --libs   a directory with FNA's Linux natives libSDL3.so.0, libFNA3D.so.0, libFAudio.so.0 (FNA's fnalibs, lib64/)
#   --out    the run directory to (re)fill
# Then:   cd <run dir> && SDL_VIDEODRIVER=offscreen CK_BUILD=dev dotnet CloudberryKingdom.dll --generate @args.json --out doc.json
#         (args.json may hold one JSON array: each element is a call, the output is an array; --repeat N; --schema s.json)
# Needs a GL driver (SDL_VIDEODRIVER=offscreen gives Mesa llvmpipe headless); no xvfb.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$HERE/../.." && pwd)"
SITE="" LIBS="" OUT="" DOTNET_EXE="${DOTNET:-}"
while [ $# -gt 0 ]; do
  case "$1" in
    --site) SITE="$2"; shift 2 ;;
    --libs) LIBS="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    --dotnet) DOTNET_EXE="$2"; shift 2 ;;
    *) sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2 ;;
  esac
done
[ -n "$SITE" ] && [ -d "$SITE/Content" ] || { echo "--site: not a built site (no Content/): $SITE" >&2; exit 2; }
[ -n "$LIBS" ] && [ -f "$LIBS/libSDL3.so.0" ] && [ -f "$LIBS/libFNA3D.so.0" ] || { echo "--libs: needs libSDL3.so.0, libFNA3D.so.0, libFAudio.so.0" >&2; exit 2; }
[ -n "$OUT" ] || { echo "--out is required" >&2; exit 2; }
[ -n "$DOTNET_EXE" ] || { [ -x "$HOME/.dotnet/dotnet" ] && DOTNET_EXE="$HOME/.dotnet/dotnet" || DOTNET_EXE=dotnet; }

# The project: Game.Browser.csproj's Compile items, a plain SDK project, no BROWSER (generated; gitignored).
PROJ="$REPO_ROOT/Game/Game.NativeDev.csproj"
python3 - "$REPO_ROOT/Game/Game.Browser.csproj" "$PROJ" <<'EOF'
import sys
src, dst = sys.argv[1:3]
items = "\n".join(l for l in open(src).read().splitlines() if "<Compile Include=" in l)
open(dst, "w").write(f"""<Project Sdk="Microsoft.NET.Sdk">
  <!-- Generated by build/tools/native-dev.sh from Game.Browser.csproj: do not edit, do not commit. -->
  <PropertyGroup>
    <OutputType>Exe</OutputType><TargetFramework>net9.0</TargetFramework>
    <RootNamespace>CloudberryKingdom</RootNamespace><AssemblyName>CloudberryKingdom</AssemblyName>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks><EnableDefaultItems>false</EnableDefaultItems><GenerateAssemblyInfo>false</GenerateAssemblyInfo>
    <Nullable>disable</Nullable><ImplicitUsings>disable</ImplicitUsings><LangVersion>latest</LangVersion>
    <DefineConstants>WINDOWS;GAME;PC_VERSION;PC;SDL2</DefineConstants>
    <NoWarn>CS0168;CS0219;CS0414;CS0649;CS0067;CS0162;CS0164;CS0169</NoWarn>
    <StartupObject>CloudberryKingdom.MainClass</StartupObject><Optimize>true</Optimize>
  </PropertyGroup>
  <ItemGroup><ProjectReference Include="../external/FNA/FNA.Core.csproj" /></ItemGroup>
  <ItemGroup>
{items}
  </ItemGroup>
</Project>
""")
EOF
"$DOTNET_EXE" build "$PROJ" -c Release -p:BaseIntermediateOutputPath=obj-native/ -p:BaseOutputPath=bin-native/ -v quiet -nologo

mkdir -p "$OUT"
cp -a "$REPO_ROOT/Game/bin-native/Release/net9.0/." "$OUT/"
cp -a "$LIBS/libSDL3.so.0" "$LIBS/libFNA3D.so.0" "$OUT/"
[ -f "$LIBS/libFAudio.so.0" ] && cp -a "$LIBS/libFAudio.so.0" "$OUT/"
rm -rf "$OUT/Content"
cp -a "$SITE/Content" "$OUT/Content"
# The game opens some content by Windows paths ("Objects\x.smo") and in another case than the file has: on Linux each
# is a missing file. Run the game until it starts, linking each missing name to the file that matches it
# case-insensitively with / for \ (S5's recipe).
for attempt in $(seq 1 40); do
  log="$(cd "$OUT" && SDL_VIDEODRIVER=offscreen timeout 120 "$DOTNET_EXE" CloudberryKingdom.dll --schema /dev/null 2>&1 || true)"
  missing="$(printf '%s\n' "$log" | grep -o "Could not find file '[^']*'" | head -1 | sed "s/^Could not find file '//; s/'\$//")" || true
  [ -n "$missing" ] || break
  rel="${missing#"$OUT/Content/"}"
  python3 - "$OUT/Content" "$rel" <<'PY'
import os, sys
root, rel = sys.argv[1], sys.argv[2]
want = rel.replace("\\", "/").lower()
for d, _, files in os.walk(root):
    for f in files:
        p = os.path.relpath(os.path.join(d, f), root)
        if p.lower() == want:
            os.symlink(p, os.path.join(root, rel)); sys.exit(0)
sys.exit("no content file matches " + rel)
PY
done
echo "built: $OUT (run: cd $OUT && SDL_VIDEODRIVER=offscreen CK_BUILD=dev $DOTNET_EXE CloudberryKingdom.dll --generate @args.json --out doc.json)"
